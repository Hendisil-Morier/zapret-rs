/// Returns the built-in default blob map (`fake_default_tls`, `fake_default_http`, `fake_default_quic`).
pub fn default_blobs() -> BTreeMap<String, Vec<u8>>
{
    let mut blobs = BTreeMap::new();
    blobs.insert("fake_default_tls".to_owned(), FAKE_TLS_CLIENTHELLO_DEFAULT.to_vec());
    blobs.insert("fake_default_http".to_owned(), FAKE_HTTP_REQUEST_DEFAULT.to_vec());
    let mut quic = vec![0u8; FAKE_QUIC_DEFAULT_LEN];
    quic[0] = 0x40;
    blobs.insert("fake_default_quic".to_owned(), quic);
    blobs
}

/// Decodes a single ASCII hexadecimal byte into its 4-bit nibble value.
const fn hex_nibble(byte: u8) -> Option<u8>
{
    match byte
    {
        b'0'..=b'9' => Some(byte - b'0'),
        b'a'..=b'f' => Some(byte - b'a' + 10),
        b'A'..=b'F' => Some(byte - b'A' + 10),
        _ => None,
    }
}

/// Parses an inline hex blob string (optionally prefixed with `0x`/`0X`), capping at `MAX_BLOB_SIZE`.
pub fn parse_hex_blob(name: &str, raw: &str) -> Result<Vec<u8>, ConfigError>
{
    let trimmed = raw.trim();
    let hex = trimmed
        .strip_prefix("0x")
        .or_else(|| trimmed.strip_prefix("0X"))
        .unwrap_or(trimmed);
    if hex.is_empty()
        || !hex.is_ascii()
        || !hex
            .len()
            .is_multiple_of(2)
    {
        return Err(ConfigError::InvalidBlob {
            name: name.to_owned(),
            detail: "hex string must be non-empty even-length ASCII hex".to_owned(),
        });
    }
    let byte_len = hex.len() / 2;
    if byte_len > MAX_BLOB_SIZE
    {
        return Err(ConfigError::InvalidBlob {
            name: name.to_owned(),
            detail: format!("hex blob size {byte_len} exceeds {MAX_BLOB_SIZE} bytes"),
        });
    }
    let (pairs, _) = hex
        .as_bytes()
        .as_chunks::<2>();
    let mut out = Vec::with_capacity(byte_len);
    for &[hi, lo] in pairs
    {
        let Some(hi_n) = hex_nibble(hi)
        else
        {
            return Err(ConfigError::InvalidBlob {
                name: name.to_owned(),
                detail: "invalid hex digit".to_owned(),
            });
        };
        let Some(lo_n) = hex_nibble(lo)
        else
        {
            return Err(ConfigError::InvalidBlob {
                name: name.to_owned(),
                detail: "invalid hex digit".to_owned(),
            });
        };
        out.push((hi_n << 4) | lo_n);
    }
    Ok(out)
}

/// Reads at most `MAX_BLOB_SIZE` bytes from `path` starting at `offset`.
pub fn load_file_blob(name: &str, path: &Path, offset: u64) -> Result<Vec<u8>, ConfigError>
{
    let mut file = File::open(path).map_err(|source| ConfigError::Io { path: path.to_path_buf(), source })?;
    if offset > 0
    {
        file.seek(SeekFrom::Start(offset))
            .map_err(|source| ConfigError::Io { path: path.to_path_buf(), source })?;
    }
    let mut buf = Vec::new();
    file.take(MAX_BLOB_SIZE as u64)
        .read_to_end(&mut buf)
        .map_err(|source| ConfigError::Io { path: path.to_path_buf(), source })?;
    if buf.is_empty()
    {
        return Err(ConfigError::InvalidBlob {
            name: name.to_owned(),
            detail: format!("file '{}' produced 0 bytes at offset {offset}", path.display()),
        });
    }
    Ok(buf)
}
